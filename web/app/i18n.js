const DICTS = { en: EN, ar: AR };
let lang = "en";

export function setLang(l) {
  lang = DICTS[l] ? l : "en";
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  try { localStorage.setItem("los.lang", lang); } catch (e) { /* storage may be blocked */ }
}

export function getLang() { return lang; }

export function initialLang(fallback) {
  try { const s = localStorage.getItem("los.lang"); if (s && DICTS[s]) return s; } catch (e) { /* blocked */ }
  return DICTS[fallback] ? fallback : "en";
}

export function t(key, vars = {}) {
  const s = (DICTS[lang] && DICTS[lang][key]) ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
